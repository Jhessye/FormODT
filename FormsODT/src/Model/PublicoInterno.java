package Model;

public class PublicoInterno {
    private String caracterizacaoPublicoInterno = "";
    private int totalPublicoInterno = 0;

    public PublicoInterno() {}

    public String getCaracterizacaoPublicoInterno() {
        return caracterizacaoPublicoInterno;
    }

    public void setCaracterizacaoPublicoInterno(String caracterizacaoPublicoInterno) {
        this.caracterizacaoPublicoInterno = caracterizacaoPublicoInterno;
    }

    public int getTotalPublicoInterno() {
        return totalPublicoInterno;
    }

    public void setTotalPublicoInterno(int totalPublicoInterno) {
        this.totalPublicoInterno = totalPublicoInterno;
    }
}
