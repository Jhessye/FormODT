package Model;

public class Fundamentacao {
    private String influenciaGruposSociais = "";
    private String mudancasPublicoExterno = "";
    private String relacaoEnsinoPesquisa = "";
    private String protagonismoEstudantes = "";
    private String instalacoesEquipamentos = "";

    public Fundamentacao() {}

    public String getInfluenciaGruposSociais() {
        return influenciaGruposSociais;
    }

    public void setInfluenciaGruposSociais(String influenciaGruposSociais) {
        this.influenciaGruposSociais = influenciaGruposSociais;
    }

    public String getMudancasPublicoExterno() {
        return mudancasPublicoExterno;
    }

    public void setMudancasPublicoExterno(String mudancasPublicoExterno) {
        this.mudancasPublicoExterno = mudancasPublicoExterno;
    }

    public String getRelacaoEnsinoPesquisa() {
        return relacaoEnsinoPesquisa;
    }

    public void setRelacaoEnsinoPesquisa(String relacaoEnsinoPesquisa) {
        this.relacaoEnsinoPesquisa = relacaoEnsinoPesquisa;
    }

    public String getProtagonismoEstudantes() {
        return protagonismoEstudantes;
    }

    public void setProtagonismoEstudantes(String protagonismoEstudantes) {
        this.protagonismoEstudantes = protagonismoEstudantes;
    }

    public String getInstalacoesEquipamentos() {
        return instalacoesEquipamentos;
    }

    public void setInstalacoesEquipamentos(String instalacoesEquipamentos) {
        this.instalacoesEquipamentos = instalacoesEquipamentos;
    }
}
